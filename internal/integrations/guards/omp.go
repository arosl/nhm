package guards

// omp's guards (nhm-yncb). dcg writes omp's guard itself: `dcg install
// --omp` (dcg 0.15.4) puts dcg-guard.ts, whose first line is ompMarker,
// into the extensions dir of omp's agent dir, or with --project into the
// project's .omp/extensions. omp 18.14.1 loads the extensions it finds in
// those two dirs (it reads the cwd's .omp only, not a Git ancestor's),
// and the extension's tool_call hook sends each bash tool call to dcg
// before the call runs. omp's disabledExtensions setting (in config.yml,
// the user's or the project's) and its --no-extensions flag keep the
// extension from loading. rch and Agent Mail install nothing for omp.

import (
	"errors"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strconv"
	"strings"

	"gopkg.in/yaml.v3"
)

// ompMarker starts the extension that `dcg install --omp` writes.
const ompMarker = "// dcg-omp-extension: generated by `dcg install --omp`"

// ompExtensionFile is the extension's file name, and ompExtensionID the
// name omp's disabledExtensions setting gives it.
const (
	ompExtensionFile = "dcg-guard.ts"
	ompExtensionID   = "extension-module:dcg-guard"
)

// ompUnsupported are the guards omp has no place for.
var ompUnsupported = map[string]string{
	RCH:           "rch installs no hook for omp (rch hook install writes Claude Code's); rch's cargo shim can offload builds: rch shim",
	AgentMailStop: "Agent Mail installs no stop hook for omp",
}

// ompDCGBin is the dcg path that the extension runs.
var ompDCGBin = regexp.MustCompile(`(?m)^const DCG_BIN = ("[^"\n]+");$`)

// ompProfileName is the profile name rule of omp 18.14.1.
var ompProfileName = regexp.MustCompile(`^[a-z0-9][a-z0-9._-]{0,63}$`)

// ompAgentDir is omp's agent dir, as omp 18.14.1 finds it: a profile's
// (OMP_PROFILE, else PI_PROFILE; "default" is none) under ~/.omp/profiles,
// else PI_CODING_AGENT_DIR, else ~/.omp/agent.
func ompAgentDir(home string, getenv func(string) string) string {
	profile := getenv("OMP_PROFILE")
	if profile == "" {
		profile = getenv("PI_PROFILE")
	}
	profile = strings.TrimSpace(profile)
	if profile != "" && profile != "default" && ompProfileName.MatchString(profile) && !strings.HasSuffix(profile, ".") {
		return filepath.Join(home, ".omp", "profiles", profile, "agent")
	}
	if dir := getenv("PI_CODING_AGENT_DIR"); dir != "" {
		return dir
	}
	return filepath.Join(home, ".omp", "agent")
}

// ompSource is a dir omp reads extensions and settings from.
type ompSource struct{ name, dir string }

func ompSources(env Env) []ompSource {
	out := []ompSource{{"user", env.OmpAgentDir}}
	if env.ProjectRoot != "" {
		out = append(out, ompSource{"project", filepath.Join(env.ProjectRoot, ".omp")})
	}
	return out
}

// checkOmp reports dcg configured when a dir that omp reads holds dcg's
// extension and no settings file disables it; rch and the stop hook are
// unsupported.
func checkOmp(env Env) []Result {
	var held, notes []string
	var off, offFix string
	for _, s := range ompSources(env) {
		path := filepath.Join(s.dir, "extensions", ompExtensionFile)
		if why := ompExtension(path); why == "" {
			held = append(held, s.name)
		} else {
			notes = append(notes, why)
		}
		switch disabled, cfg, err := ompDisables(s.dir); {
		case err != nil && off == "":
			off, offFix = "omp's settings cannot be read ("+err.Error()+"), so nhm cannot tell whether they disable dcg's extension", "fix "+cfg
		case disabled && off == "":
			off, offFix = "omp's disabledExtensions in "+cfg+" holds "+ompExtensionID+", so omp does not load dcg's extension",
				"remove "+ompExtensionID+" from disabledExtensions in "+cfg
		}
	}
	return each("omp", func(g string) Result {
		if why, ok := ompUnsupported[g]; ok {
			return Result{State: Unsupported, Detail: why}
		}
		switch {
		case off != "":
			return Result{State: Missing, Detail: off, Fix: offFix}
		case len(held) == 0:
			return Result{State: Missing, Detail: "no dir that omp reads holds dcg's omp extension: " + strings.Join(notes, "; "), Fix: fixFor("omp", g)}
		}
		return Result{State: Configured, Sources: held, Detail: "dcg's omp extension screens each bash tool call"}
	})
}

// ompExtension says why path is not dcg's working omp extension, or ""
// when it is: the file starts with dcg's marker, and the dcg that its
// DCG_BIN line names, when it has one, is an executable file.
func ompExtension(path string) string {
	data, err := os.ReadFile(path)
	switch {
	case errors.Is(err, os.ErrNotExist):
		return path + " does not exist"
	case err != nil:
		return path + ": " + err.Error()
	case !strings.HasPrefix(string(data), ompMarker):
		return path + " is not the extension that dcg install --omp writes"
	}
	m := ompDCGBin.FindSubmatch(data)
	if m == nil {
		return ""
	}
	bin, err := strconv.Unquote(string(m[1]))
	if err != nil {
		return ""
	}
	if fi, err := os.Stat(bin); err != nil || !fi.Mode().IsRegular() || fi.Mode().Perm()&0o111 == 0 {
		return path + " runs " + bin + ", which is not an executable file (dcg install --omp --force writes it again)"
	}
	return ""
}

// ompDisables reports whether omp's settings in dir (config.yml, else
// config.yaml) disable dcg's extension; cfg is the file read.
func ompDisables(dir string) (bool, string, error) {
	for _, name := range []string{"config.yml", "config.yaml"} {
		cfg := filepath.Join(dir, name)
		data, err := os.ReadFile(cfg)
		if errors.Is(err, os.ErrNotExist) {
			continue
		}
		if err != nil {
			return false, cfg, err
		}
		var s struct {
			DisabledExtensions []string `yaml:"disabledExtensions"`
		}
		if err := yaml.Unmarshal(data, &s); err != nil {
			return false, cfg, errors.New(cfg + ": " + err.Error())
		}
		return slices.Contains(s.DisabledExtensions, ompExtensionID), cfg, nil
	}
	return false, "", nil
}

// ompKeeps applies omp's launch flags to the sources that hold the
// extension: --no-extensions loads none, and --profile reads another
// agent dir than the user source.
func ompKeeps(argv, sources []string) (bool, string) {
	if slices.Contains(argv, "--no-extensions") {
		return false, "the launch argv has --no-extensions, which keeps omp from loading dcg's extension"
	}
	profile := slices.ContainsFunc(argv, func(a string) bool { return a == "--profile" || strings.HasPrefix(a, "--profile=") })
	if profile && !slices.Contains(sources, "project") {
		return false, "the launch argv's --profile reads another agent dir than the one that holds dcg's extension"
	}
	return true, ""
}
